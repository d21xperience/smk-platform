func TestAutoGeneratedID(t *testing.T) {
	d := NewMemoryDLQ(0)

	dl := DeadLetter{
		OriginalEvent: createTestEvent(),
		ConsumerName:  "consumer",
	}
	_ = d.Store(dl)

	list := d.List()
	if len(list) != 1 {
		t.Fatalf("Expected 1 dead letter, got %d", len(list))
	}
	if list[0].ID == "" {
		t.Error("Expected auto-generated ID")
	}
	if list[0].FailedAt.IsZero() {
		t.Error("Expected FailedAt to be set")
	}
}

func TestFailedAtAutoSet(t *testing.T) {
	d := NewMemoryDLQ(0)

	before := time.Now()
	dl := DeadLetter{
		OriginalEvent: createTestEvent(),
		ConsumerName:  "consumer",
	}
	_ = d.Store(dl)
	after := time.Now()

	list := d.List()
	if list[0].FailedAt.Before(before) || list[0].FailedAt.After(after) {
		t.Error("Expected FailedAt to be auto-set to current time")
	}
}
